// Generates src/lib/commerce/preview-assets.generated.mjs from design/commerce-preview/assets/*.webp.
// Images are embedded so they are only reachable through the gated
// /commerce-preview/assets/[file] route (never from /public on Production).
// Usage: node scripts/commerce-preview/build-preview-assets.mjs   (or --check to verify only)
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const srcDir = join(root, "design", "commerce-preview", "assets");
const outFile = join(root, "src", "lib", "commerce", "preview-assets.generated.mjs");

/** Minimal WebP dimension reader (VP8, VP8L, VP8X). */
function webpSize(buf) {
  if (buf.toString("ascii", 0, 4) !== "RIFF" || buf.toString("ascii", 8, 12) !== "WEBP") throw new Error("not webp");
  const chunk = buf.toString("ascii", 12, 16);
  if (chunk === "VP8X") return { width: 1 + buf.readUIntLE(24, 3), height: 1 + buf.readUIntLE(27, 3) };
  if (chunk === "VP8L") { const b = buf.readUInt32LE(21); return { width: (b & 0x3fff) + 1, height: ((b >> 14) & 0x3fff) + 1 }; }
  if (chunk === "VP8 ") return { width: buf.readUInt16LE(26) & 0x3fff, height: buf.readUInt16LE(28) & 0x3fff };
  throw new Error("unknown webp chunk " + chunk);
}

const entries = readdirSync(srcDir).filter((f) => f.endsWith(".webp")).sort().map((name) => {
  const buf = readFileSync(join(srcDir, name));
  return { name, ...webpSize(buf), sha256: createHash("sha256").update(buf).digest("hex"), base64: buf.toString("base64") };
});

const body = `// GENERATED by scripts/commerce-preview/build-preview-assets.mjs — do not edit.
// Design-review mockups only; NOT production print files.
export const PREVIEW_ASSETS = Object.freeze({
${entries.map((e) => `  ${JSON.stringify(e.name)}: Object.freeze({ width: ${e.width}, height: ${e.height}, sha256: ${JSON.stringify(e.sha256)}, base64: ${JSON.stringify(e.base64)} }),`).join("\n")}
});
`;

if (process.argv.includes("--check")) {
  const current = readFileSync(outFile, "utf8").replace(/\r\n/g, "\n"); // tolerate Windows autocrlf checkouts
  if (current !== body) { console.error("preview-assets.generated.mjs is stale; run the generator"); process.exit(1); }
  console.log("preview assets up to date");
} else {
  writeFileSync(outFile, body);
  console.log(entries.map((e) => `${e.name} ${e.width}x${e.height}`).join("\n"));
}
